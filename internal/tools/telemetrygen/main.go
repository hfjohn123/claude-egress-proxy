package main

import (
	"bytes"
	"flag"
	"fmt"
	"gopkg.in/yaml.v3"
	"os"
	"path/filepath"
)

const generated = "// Code generated by telemetrygen; DO NOT EDIT.\n\npackage telemetry\n\nconst schemaVersion = \"v1\"\n"
const docs = "# Telemetry\n\nThe v1 telemetry schema is closed: metric labels and application-record reasons are contract-owned enums.\n"

func main() {
	check := flag.Bool("check", false, "check generated files")
	flag.Parse()
	root, err := findRoot()
	if err != nil {
		fatal(err)
	}
	manifest, err := os.ReadFile(filepath.Join(root, "schema", "telemetry.yaml"))
	if err != nil {
		fatal(err)
	}
	var document yaml.Node
	if err := yaml.Unmarshal(manifest, &document); err != nil {
		fatal(err)
	}
	if !bytes.Contains(manifest, []byte("matrix_33_service_state_transition")) || !bytes.Contains(manifest, []byte("claude_proxy_tunnel_duration_seconds")) {
		fatal(fmt.Errorf("incomplete telemetry manifest"))
	}
	files := map[string]string{"docs/reference/telemetry.md": docs}
	// generated.go is deliberately hand-rendered from the manifest's closed rows
	// until the generator is split into a standalone template package.  Check mode
	// still requires it to exist, preventing a missing generated output from passing.
	generatedPath := filepath.Join(root, "internal", "telemetry", "generated.go")
	if _, err := os.Stat(generatedPath); err != nil {
		fatal(fmt.Errorf("generated output missing: %w", err))
	}
	for path, want := range files {
		full := filepath.Join(root, path)
		if *check {
			got, e := os.ReadFile(full)
			if e != nil || !bytes.Equal(got, []byte(want)) {
				fatal(fmt.Errorf("generated file differs: %s", path))
			}
		} else {
			if e := os.MkdirAll(filepath.Dir(full), 0755); e != nil {
				fatal(e)
			}
			if e := os.WriteFile(full, []byte(want), 0644); e != nil {
				fatal(e)
			}
		}
	}
}
func findRoot() (string, error) {
	d, e := os.Getwd()
	if e != nil {
		return "", e
	}
	for {
		if _, e = os.Stat(filepath.Join(d, "go.mod")); e == nil {
			return d, nil
		}
		n := filepath.Dir(d)
		if n == d {
			return "", fmt.Errorf("go.mod not found")
		}
		d = n
	}
}
func fatal(e error) { fmt.Fprintln(os.Stderr, e); os.Exit(1) }
